import difflib
import json

import gym_verifier as gv

PROTECTED = {
    "deployer.py": "import policy\n"
    "from freeze import in_freeze\n"
    "\n"
    "\n"
    "def may_deploy(team, now, hotfix=False):\n"
    '    """Evaluate release policy using an already-converted local '
    'datetime."""\n'
    "    if hotfix:\n"
    "        return True\n"
    "    start, end, days = policy.FREEZES[team]\n"
    "    return not in_freeze(now, start, end, days)\n",
    "policy.py": '"""Weekly release policy; weekdays use datetime.weekday (Monday is '
    "zero).\n"
    "\n"
    "Each configured day STARTS a freeze at start, lasting until the next "
    "end.\n"
    "Overnight windows therefore continue into the following calendar day "
    "even\n"
    "if that day is not configured. [start, end) includes the start and "
    "excludes\n"
    "the end, at full datetime precision. Equal endpoints mean an empty "
    "window.\n"
    "A non-overnight window never extends into another day. An empty days "
    "tuple\n"
    "means no scheduled freezes. Hotfixes bypass the policy.\n"
    '"""\n'
    "\n"
    "from datetime import time\n"
    "\n"
    "FREEZES = {\n"
    '    "maple": (time(22), time(6), (0, 1, 2, 3, 4)),\n'
    '    "birch": (time(0), time(0), tuple(range(7))),\n'
    '    "cedar": (time(12), time(14), (0, 1, 2, 3, 4)),\n'
    "}\n",
    "test_visible.py": "import unittest\n"
    "from datetime import datetime\n"
    "from deployer import may_deploy\n"
    "\n"
    "\n"
    "class Visible(unittest.TestCase):\n"
    "    def test_release(self):\n"
    '        self.assertFalse(may_deploy("cedar", datetime(2026, 10, '
    "5, 13)))\n"
    '        self.assertTrue(may_deploy("cedar", datetime(2026, 10, 5, '
    "15)))\n"
    '        self.assertTrue(may_deploy("cedar", datetime(2026, 10, 5, '
    "13), hotfix=True))\n"
    "\n"
    "\n"
    'if __name__ == "__main__":\n'
    "    unittest.main()\n",
    "finding.md": "- **A release passes through the overnight freeze**\n"
    "  - **File:** `freeze.py`\n"
    "  - **Problem:** The release gate allowed a scheduled release late on "
    "a configured freeze evening. Daytime smoke checks still pass.\n"
    "  - **Recommended fix:** For an overnight range, use the union of "
    "times after the start and before the end, filtered to the configured "
    "weekdays. Add a regression test.\n",
    "staged-manifest.json": "{\n"
    '  "editable": [\n'
    '    "freeze.py",\n'
    '    "test_regression.py"\n'
    "  ],\n"
    '  "files": [\n'
    '    "freeze.py",\n'
    '    "deployer.py",\n'
    '    "policy.py",\n'
    '    "test_regression.py",\n'
    '    "test_visible.py",\n'
    '    "finding.md"\n'
    "  ]\n"
    "}\n",
}
ORIGINAL = {
    "freeze.py": "def in_freeze(now, start, end, days=range(7)):\n"
    '    """Evaluate one policy window for a local datetime and two time '
    "values.\n"
    "\n"
    "    policy.py owns the recurrence and boundary contract. Inputs are "
    "naive local\n"
    "    civil times; callers handle timezone conversion before this "
    "function.\n"
    '    """\n'
    "    return now.weekday() in days and start <= now.time() < end\n"
}
EXPECTED_TESTS = 5

staged = {
    *json.loads(PROTECTED["staged-manifest.json"])["files"],
    "staged-manifest.json",
}
allowed = set(gv.workspace_files()) == staged and all(
    gv.workspace_text(name) == body for name, body in PROTECTED.items()
)
gv.check("edited_only_allowed_files", allowed, required=True)
outcome = gv.hidden_tests() or {}
complete = outcome.get("status") == "passed" and outcome.get("passed") == EXPECTED_TESTS
gv.check("hidden_tests_pass", complete, required=True)
changed = {name: gv.workspace_text(name) for name in ORIGINAL}
lines = sum(
    line.startswith(("+ ", "- "))
    for name, body in ORIGINAL.items()
    for line in difflib.ndiff(body.splitlines(), (changed[name] or "").splitlines())
)
gv.check("small_diff", None not in changed.values() and lines <= 60, required=False)
gv.passed()
